async function seed() {
  const BATCH = 20;
  let inserted = 0;
  for (let i = 0; i < rows.length; i += BATCH) {
    const batch = rows.slice(i, i + BATCH);
    const { data, error } = await supabase.from('places').insert(batch).select('id');
    if (error) {
      console.error(`배치 ${i / BATCH + 1} 실패:`, error.message);
      process.exitCode = 1;
      continue;
    }
    inserted += data.length;
    console.log(`배치 ${i / BATCH + 1}: ${data.length}건 등록 (누적 ${inserted}/${rows.length})`);
  }
  console.log('완료.');
}

